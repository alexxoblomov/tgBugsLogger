import json
from environs import Env
from openai import AsyncOpenAI

env = Env()
env.read_env()

# Настройка OpenRouter
openrouter_api_key = env('OPENROUTER_API_KEY', default=None)
client = AsyncOpenAI(
    base_url="https://openrouter.ai/api/v1",
    api_key=openrouter_api_key
) if openrouter_api_key else None

# Модель ИИ
# ВЗЯТЬ КАКУЮ-НИБУДЬ МОДЕЛЬ МОЖНО В openrouter.ai
MODEL_NAME = "ИМЯ МОДЕЛИ"

# Степень обрезания сообщения
MIN_MSG_LENGTH = 20
MIN_MSG_WORDS = 3

# ПРИМЕР ПРОМТА, КОТОРЫЙ БУДЕТ ПОЛЬЗОВАТЬСЯ AI
SYSTEM_PROMPT = """Ты — ИИ-модератор баг-репортов мобильной игры. Классифицируй сообщение: баг-репорт или нет.

══ ОДОБРИТЬ (is_valid: true) — ОБА условия выполнены ══

1) ПРОБЛЕМА — описана любая проблема в игре:
   - Вылеты, краши, зависания, бесконечная загрузка
   - Графика: артефакты, текстуры пропадают, мерцание, чёрный экран
   - Звук: нет звука, хрип, зацикливание
   - Интерфейс: кнопка не работает, наложение текста, не открывается меню
   - Сеть: дисконнект, не подключается, десинхрон, не заходит на сервер
   - Физика/мир: провал сквозь карту, застревание, полёт в воздухе
   - Прогресс: пропали предметы, сбросился уровень, откат сохранения
   - Покупки: деньги списались но предмет не получен
   - Любая другая жалоба на неработающий функционал

2) УСТРОЙСТВО или платформа:
   Явно: "Samsung A52", "iPhone 13", "Redmi Note 10", "iPad"
   Неявно: "на андроиде", "ios", "на телефоне", "на планшете", "на эмуляторе"
   Сленг: "самсунг", "айфон", "сяоми", "хуавей", "редми", "поко"

══ ОТКЛОНИТЬ (is_valid: false) — хотя бы ОДНО совпадение ══

- ФЛУД: приветствия, прощания, благодарности, эмоции без сути
- ВОПРОСЫ без описания проблемы: "когда фикс?", "у кого такое?"
- ОБСУЖДЕНИЯ: цитирование ("> текст"), "согласен", "у меня тоже", "подтверждаю"
- БАЛАНС/ГЕЙМПЛЕЙ: "дорого", "имба", "мало опыта", "нерф", "бафф" — не баги
- ФИЧРЕКВЕСТЫ: "добавьте", "хочу чтобы", "было бы круто", "предлагаю"
- НЕТ УСТРОЙСТВА: описана проблема, но не указано устройство/платформа
- ТОЛЬКО БРАНЬ: мат без описания проблемы

══ НЮАНСЫ (важно для точности) ══

- Мат/сленг + реальная проблема + устройство → ОДОБРИТЬ (не отклоняй за грубость)
- Сообщение на любом языке (рус/англ/смесь) → оценивай суть
- К сообщению могут быть приложены медиа — оценивай только текст
- Неидеальная формулировка, но суть проблемы понятна + есть устройство → ОДОБРИТЬ
- Наличие ID/ника игрока — плюс, но НЕ обязательно

══ ПРИМЕРЫ ══

ОДОБРИТЬ:
- "Samsung A52, android 13. Вылетает при входе в гараж" → проблема + устройство
- "айфон 14 про. Чёрные текстуры дорог в онлайне" → проблема + устройство
- "poco f7. Текстуры пропадают когда двигаешь sw500" → проблема + устройство
- "на андроиде — при столкновении зависает на 5 сек" → проблема + платформа
- "Samsung Galaxy S24 ultra. Не могу зайти на выбранный сервер" → проблема + устройство
- "ios, провалился под карту возле стадиона" → проблема + платформа

ОТКЛОНИТЬ:
- "игра лагает" → нет устройства
- "когда обнова??" → вопрос, не проблема
- "разрабы фиксите баги!!!" → эмоции без описания
- "добавьте новые машины плиз" → фичреквест
- "мало денег за гонку" → баланс, не баг
- "> вылетает игра\nда у меня тоже" → обсуждение
- "топ игра 🔥" → оффтоп
- "у меня такая же проблема" → нет деталей
- "постоянно лагает" → нет устройства

══ ОТВЕТ ══

Верни ТОЛЬКО JSON (без markdown):
{"is_valid": true/false, "reason": "краткое пояснение на русском"}"""


async def validate_bug_report(text: str) -> dict:
    """
    Проверяет сообщение через AI и возвращает результат валидации.
    
    Returns:
        dict: {
            "is_valid": bool,
            "reason": str | None
        }
    """
    if not text or not text.strip():
        return {
            "is_valid": False,
            "reason": "Пустое сообщение"
        }

    cleaned = text.strip()
    words = cleaned.split()

    if len(cleaned) < MIN_MSG_LENGTH or len(words) < MIN_MSG_WORDS:
        return {
            "is_valid": False,
            "reason": f"Сообщение слишком короткое для баг-репорта ({len(words)} сл., {len(cleaned)} симв.)"
        }

    if not client:
        return {
            "is_valid": False,
            "reason": "AI не настроен (OPENROUTER_API_KEY отсутствует)"
        }
    
    try:
        response = await client.chat.completions.create(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": text}
            ],
            temperature=0.1
        )
        
        response_text = (response.choices[0].message.content or "").strip()
        
        # Очищаем ответ от возможных markdown-блоков
        if response_text.startswith("```"):
            response_text = response_text.split("```")[1]
            if response_text.startswith("json"):
                response_text = response_text[4:]
        response_text = response_text.strip()

        # Если модель вернула JSON с поясняющим текстом, достаём сам объект.
        if not response_text.startswith("{"):
            json_start = response_text.find("{")
            json_end = response_text.rfind("}")
            if json_start != -1 and json_end != -1 and json_end > json_start:
                response_text = response_text[json_start:json_end + 1]
        
        return json.loads(response_text)
        
    except Exception as e:
        # В случае ошибки AI — пропускаем сообщение
        print(f"AI validation error: {e}")
        return {
            "is_valid": False,
            "reason": "AI недоступен, требуется ручная проверка"
        }
